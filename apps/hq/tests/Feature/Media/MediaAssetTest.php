<?php

use App\Context\Provenance;
use App\Media\LocalStorageDriver;
use App\Media\MediaAssetService;
use App\Models\AuditLog;
use App\Models\MediaAsset;
use Illuminate\Support\Facades\Storage;

/*
 | Phase 2.5 E: media metadata in Postgres, bytes behind a driver, no path in the domain model.
 */

beforeEach(function () {
    Storage::fake('local');
});

it('stores bytes behind the driver and records only a driver and an opaque key', function () {
    $asset = app(MediaAssetService::class)->store('the bytes', 'image/png', 'image', Provenance::Business, [
        'rights' => ['license' => 'owned', 'allowed_uses' => ['social', 'catalogue']],
    ]);

    expect($asset->storage_driver)->toBe('local')
        ->and($asset->bytes)->toBe(9)
        ->and($asset->checksum_sha256)->toBe(hash('sha256', 'the bytes'))
        ->and($asset->provenance)->toBe(Provenance::Business);

    // The row names a key, never a path. Nothing above the driver could build one.
    $columns = array_keys($asset->getAttributes());
    expect($columns)->not->toContain('path')
        ->and($columns)->not->toContain('disk')
        ->and($asset->storage_key)->not->toContain(base_path());

    expect(app(MediaAssetService::class)->contents($asset))->toBe('the bytes');
});

it('verifies that what is on disk still matches what was recorded', function () {
    $service = app(MediaAssetService::class);
    $asset = $service->store('original', 'image/png', 'image', Provenance::Business);

    expect($service->verify($asset))->toBeTrue();

    // Corrupt it underneath, the way a bad restore would.
    (new LocalStorageDriver)->put($asset->storage_key, 'tampered', 'image/png');

    expect($service->verify($asset))->toBeFalse();
});

it('does not store the same bytes twice', function () {
    $service = app(MediaAssetService::class);

    $first = $service->store('same', 'image/png', 'image', Provenance::Business);
    $second = $service->store('same', 'image/png', 'image', Provenance::Business);

    // Two rows for one file would let their rights records later disagree about it.
    expect($second->id)->toBe($first->id)
        ->and(MediaAsset::count())->toBe(1);
});

it('fails closed on rights nobody recorded', function () {
    $service = app(MediaAssetService::class);

    $unlicensed = $service->store('unknown provenance', 'image/jpeg', 'image', Provenance::ThirdParty);
    $licensed = $service->store('ours', 'image/jpeg', 'image', Provenance::Business, [
        'rights' => ['license' => 'owned', 'allowed_uses' => ['social']],
    ]);

    // The cost of forgetting is an asset that cannot be published, not a publication nobody had the
    // right to make.
    expect($unlicensed->permitsUse('social'))->toBeFalse()
        ->and($licensed->permitsUse('social'))->toBeTrue()
        ->and($licensed->permitsUse('advertising'))->toBeFalse();
});

it('keeps generator and consent metadata for synthetic media', function () {
    $asset = app(MediaAssetService::class)->store('generated bytes', 'image/png', 'image', Provenance::Generated, [
        'generator' => ['provider' => 'some-provider', 'model' => 'some-model', 'prompt_ref' => 'prompt:42'],
        'consent_event_id' => 999,
        'data_class' => 'personal',
    ]);

    expect($asset->provenance)->toBe(Provenance::Generated)
        ->and($asset->provenance->isTrusted())->toBeFalse()
        ->and($asset->generator['model'])->toBe('some-model')
        ->and($asset->consent_event_id)->toBe(999);
});

it('refuses a storage key that tries to escape its prefix', function () {
    $driver = new LocalStorageDriver;

    expect(fn () => $driver->put('../../etc/passwd', 'x', 'text/plain'))
        ->toThrow(InvalidArgumentException::class, 'traversal');
    expect(fn () => $driver->get('/etc/passwd'))->toThrow(InvalidArgumentException::class);
});

it('audits that an asset was stored', function () {
    app(MediaAssetService::class)->store('audited', 'application/pdf', 'document', Provenance::Business);

    $audit = AuditLog::where('action', 'media_asset.stored')->sole();
    expect($audit->after['kind'])->toBe('document')
        ->and($audit->after['driver'])->toBe('local');
});
