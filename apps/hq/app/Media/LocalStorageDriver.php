<?php

namespace App\Media;

use App\Platform\Contracts\StorageDriver;
use Illuminate\Support\Facades\Storage;
use InvalidArgumentException;

/**
 * Bytes on the VPS disk, behind the driver interface (Phase 2.5 E).
 *
 * The only driver in Phase 2.5, and deliberately the least interesting class in the subsystem:
 * everything above it names a driver and an opaque key, so replacing this with object storage is a
 * new class and a configuration value rather than a data migration and a hunt for every URL somebody
 * built out of a path.
 *
 * ⚠ ADR-014 chose local-only backup because HQ's data was derived and reconstructable from the ERP
 * and the shops. Bytes stored here are the first thing in HQ that is NOT reconstructable from
 * anywhere else, which is why `MediaAssetService` records that fact on every asset and why the
 * backup posture has to be revisited before Phase 6 generates anything at volume.
 */
final readonly class LocalStorageDriver implements StorageDriver
{
    public function __construct(private string $disk = 'local', private string $prefix = 'media') {}

    public function name(): string
    {
        return 'local';
    }

    public function put(string $key, string $contents, string $contentType): string
    {
        Storage::disk($this->disk)->put($this->path($key), $contents);

        return $key;
    }

    public function get(string $key): ?string
    {
        $path = $this->path($key);

        return Storage::disk($this->disk)->exists($path)
            ? Storage::disk($this->disk)->get($path)
            : null;
    }

    public function exists(string $key): bool
    {
        return Storage::disk($this->disk)->exists($this->path($key));
    }

    public function delete(string $key): bool
    {
        return Storage::disk($this->disk)->delete($this->path($key));
    }

    public function size(string $key): ?int
    {
        $path = $this->path($key);

        return Storage::disk($this->disk)->exists($path) ? Storage::disk($this->disk)->size($path) : null;
    }

    /**
     * The key is opaque to callers and must stay inside the prefix.
     *
     * A key is generated by this application, never supplied by a caller, but the check is here
     * anyway: the day one is built from a filename that came from outside, traversal would
     * otherwise be a working feature rather than a rejected request.
     */
    private function path(string $key): string
    {
        if ($key === '' || str_contains($key, '..') || str_starts_with($key, '/') || str_contains($key, "\0")) {
            throw new InvalidArgumentException('A storage key may not be empty, absolute, or contain a traversal sequence.');
        }

        return $this->prefix.'/'.$key;
    }
}
